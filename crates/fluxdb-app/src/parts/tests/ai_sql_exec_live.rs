/// 元数据搜索/描述 + 受控只读查询 + 进度 + 取消 + 会话隔离（PostgreSQL）。
#[test]
fn t023_postgres_metadata_query_cancel_and_session_isolation() {
    let Some(params) = ai_live_params("PostgreSQL", "FLUXDB_PG_SMOKE") else {
        tracing::warn!(target: "fluxdb_app", "未设置 FLUXDB_PG_SMOKE，跳过 T023 PG 冒烟");
        return;
    };
    let config = ai_live_pg_config(&params);
    let database = params.4.clone();
    let connector = fluxdb_connectors::connector_for(&config).expect("PG connector");
    ai_live_pg_setup(connector.as_ref(), &config, &database);

    let resolver = AiLiveResolver::new(config.clone());
    let target = AiSqlTarget::parse(&format!(
        "conn:{}/db:{}/schema:fluxdb_ai_smoke",
        config.id.0, database
    ))
    .expect("target 句柄");

    // 1) 搜索：真实库按名字模糊搜索，limit 生效。
    let found = search_objects(&resolver, &target, "orders", 10, &|| false).expect("搜索应成功");
    let objects = found["objects"].as_array().expect("objects 是数组");
    assert!(
        objects.iter().any(|item| item["name"] == "orders"),
        "应搜到真实表 orders，实际 {found}"
    );

    // 2) 描述：列/索引/外键/注释/DDL 均来自真实 catalog。
    let described = describe_object(
        &resolver,
        &target,
        &serde_json::json!({"name": "orders", "kind": "table"}),
        &["columns".into(), "indexes".into(), "foreign_keys".into(), "comment".into(), "ddl".into()],
        &|| false,
    )
    .expect("对象描述应成功");
    let columns = described["columns"].as_array().expect("columns 是数组");
    assert!(
        columns.iter().any(|column| column["name"] == "amount"),
        "列元数据应含真实列 amount：{described}"
    );
    assert!(
        described["indexes"]
            .as_array()
            .is_some_and(|indexes| indexes.iter().any(|index| index["name"]
                .as_str()
                .is_some_and(|name| name.contains("idx_fluxdb_ai_orders_customer")))),
        "应读到真实索引：{described}"
    );
    assert!(
        described["foreign_keys"]
            .as_array()
            .is_some_and(|fks| !fks.is_empty()),
        "应读到真实外键：{described}"
    );
    assert_eq!(described["comment"], "T023 orders");
    assert!(
        described["ddl"].as_str().is_some_and(|ddl| ddl.contains("orders")),
        "应读到真实 DDL：{described}"
    );

    // 3) 受控只读查询：真实行/列 + max_rows 截断 + source/session/progress 回执。
    let outcome = execute_sql(
        &resolver,
        &target,
        "SELECT id, amount FROM fluxdb_ai_smoke.orders ORDER BY id",
        1,
        true,
        &|| false,
    )
    .expect("只读查询应成功");
    assert_eq!(outcome.columns, vec!["id".to_string(), "amount".to_string()]);
    assert_eq!(outcome.row_count, 1, "max_rows=1 必须生效");
    assert!(outcome.truncated, "被截断必须标记");
    assert_eq!(outcome.source, fluxdb_core::CommandExecutionSource::Ai);
    assert!(outcome.query_session_id.is_host_managed());
    assert!(
        !outcome.progress.is_empty(),
        "真实 Connector 应产生进度摘要"
    );
    assert_eq!(outcome.executed_sql.contains("LIMIT"), true);

    // 4) 进度事件通道：真实 Connector summary 进入 ToolExecutionContext.progress。
    let events = std::sync::Arc::new(std::sync::Mutex::new(Vec::new()));
    let tool = AiSqlReadTool::query(std::sync::Arc::new(AiLiveResolver::new(config.clone())))
        .expect("db.query 工具");
    let receipt = ai_block_on(tool.execute(
        fluxdb_core::ToolExecutionContext {
            session_id: "t023-live".into(),
            turn_id: "t023-live-turn".into(),
            iteration: 1,
            call_id: "t023-progress".into(),
            progress: Some(events.clone()),
            cancel: fluxdb_core::CancelFlag::new(),
        },
        serde_json::json!({
            "target": format!("conn:{}/db:{}", config.id.0, database),
            "sql": "SELECT id FROM fluxdb_ai_smoke.orders ORDER BY id",
            "max_rows": 10
        })
        .to_string(),
    ))
    .expect("工具调用");
    assert_eq!(receipt.status, fluxdb_core::ToolReceiptStatus::Succeeded);
    let progress = events.lock().expect("进度锁");
    assert!(
        progress.iter().any(|event| event.success && event.returned_rows > 0),
        "真实进度事件应报告返回行数：{progress:?}"
    );
    drop(progress);

    // 5) 取消：真实连接上取消返回 Cancelled，不伪造成功。
    let cancel = fluxdb_core::CancelFlag::new();
    cancel.request();
    let cancelled = ai_block_on(tool.execute(
        fluxdb_core::ToolExecutionContext {
            session_id: "t023-live".into(),
            turn_id: "t023-live-turn".into(),
            iteration: 2,
            call_id: "t023-cancel".into(),
            progress: None,
            cancel,
        },
        serde_json::json!({
            "target": format!("conn:{}/db:{}", config.id.0, database),
            "sql": "SELECT id FROM fluxdb_ai_smoke.orders"
        })
        .to_string(),
    ))
    .expect("工具调用");
    assert_eq!(cancelled.status, fluxdb_core::ToolReceiptStatus::Cancelled);

    // 6) 隔离：AI 每次只读调用在独立会话里，临时表不残留到下一次调用。
    let create_temp = execute_sql(
        &resolver,
        &target,
        "CREATE TEMP TABLE t023_ai_scratch(id int)",
        10,
        true,
        &|| false,
    );
    // CREATE TEMP TABLE 属写操作；只读入口必须拒绝（不能靠 SELECT 前缀绕过）。
    assert_eq!(
        create_temp.expect_err("只读入口必须拒绝 CREATE").code,
        "not_read_only"
    );
    // 用写入口建临时表，随后另一次只读调用不应看到它（会话已释放）。
    execute_sql(
        &resolver,
        &target,
        "CREATE TEMP TABLE t023_ai_scratch(id int)",
        10,
        false,
        &|| false,
    )
    .expect("写入口建临时表应成功");
    // `pg_temp.n` 只在本会话解析：表若随上一条调用释放，`to_regclass` 返回 NULL。
    // （不能用 pg_catalog.pg_class 计数：它跨会话可见，无法证明隔离。）
    let leaked = execute_sql(
        &resolver,
        &target,
        "SELECT to_regclass('pg_temp.t023_ai_scratch')",
        10,
        true,
        &|| false,
    )
    .expect("复查临时表可见性应成功");
    assert_eq!(
        leaked.rows.first().and_then(|row| row.first()),
        Some(&serde_json::Value::Null),
        "上一条 AI 调用的临时表不得泄漏到后续调用：{leaked:?}"
    );
}

