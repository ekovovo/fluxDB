// T023 真实库验收（设计 §20–21）：元数据搜索/描述、受控只读查询、取消、进度、
// 以及 AI 会话与编辑器会话互不串扰。
//
// 门控（未配置则整体跳过，不触达任何数据库）：
//   FLUXDB_PG_SMOKE=host:port:user:password:db
//   FLUXDB_MYSQL_SMOKE=host:port:user:password:db
//
// 安全边界：只在同名隔离 schema/database 内建对象；凭据只用于构造连接配置，
// 绝不打印；断言失败信息也不回显密码。

fn ai_live_params(label: &str, env: &str) -> Option<(String, u16, String, String, String)> {
    let value = std::env::var(env).ok()?;
    let mut parts = value.split(':');
    let host = parts.next()?.to_string();
    let port: u16 = parts.next()?.parse().ok()?;
    let user = parts.next()?.to_string();
    let password = parts.next()?.to_string();
    let db = parts.next()?.to_string();
    if parts.next().is_some() {
        tracing::warn!(target: "fluxdb_app", env, "跳过 {label}：环境变量格式非法");
        return None;
    }
    Some((host, port, user, password, db))
}

fn ai_live_pg_config(
    (host, port, user, password, db): &(String, u16, String, String, String),
) -> ConnectionConfig {
    ConnectionConfig {
        id: ConnectionId(9_101),
        name: "T023 PG Smoke".to_string(),
        kind: DatabaseKind::Postgres,
        endpoint: Endpoint::Tcp {
            host: host.clone(),
            port: *port,
            database: Some(db.clone()),
        },
        options: Default::default(),
        redis_profile: None,
        mysql_profile: None,
        postgres_profile: Some(fluxdb_core::PostgresConnectionProfile {
            basic: fluxdb_core::PostgresBasicOptions {
                host: host.clone(),
                port: *port,
                maintenance_database: db.clone(),
                username: user.clone(),
                password: fluxdb_core::SecretRef::inline(password),
            },
            ..Default::default()
        }),
    }
}

fn ai_live_mysql_config(
    (host, port, user, password, db): &(String, u16, String, String, String),
) -> ConnectionConfig {
    let mut options = std::collections::BTreeMap::new();
    options.insert("username".to_string(), user.clone());
    options.insert("password".to_string(), password.clone());
    ConnectionConfig {
        id: ConnectionId(9_102),
        name: "T023 MySQL Smoke".to_string(),
        kind: DatabaseKind::MySql,
        endpoint: Endpoint::Tcp {
            host: host.clone(),
            port: *port,
            database: Some(db.clone()),
        },
        options,
        redis_profile: None,
        mysql_profile: None,
        postgres_profile: None,
    }
}

fn ai_live_exec(
    connector: &dyn Connector,
    connection_id: ConnectionId,
    database: Option<String>,
    schema: Option<String>,
    text: &str,
) -> fluxdb_core::Result<fluxdb_core::QueryExecutionResult> {
    connector.execute(&QueryRequest {
        connection_id,
        database,
        schema,
        text: text.to_string(),
        mode: fluxdb_core::QueryMode::All,
        options: fluxdb_core::QueryExecutionOptions {
            continue_on_error: false,
            split_statements: true,
            page_offset: 0,
            page_size: 100,
        },
        session_id: None,
    })
}

fn ai_live_assert_all_ok(
    execution: &fluxdb_core::QueryExecutionResult,
    context: &str,
) {
    let failed: Vec<_> = execution
        .summaries
        .iter()
        .filter(|summary| !summary.success)
        .collect();
    assert!(failed.is_empty(), "{context} 失败: {failed:#?}");
}

/// 建立隔离 schema：orders(带注释/索引/外键) + order_stats 视图。
fn ai_live_pg_setup(connector: &dyn Connector, config: &ConnectionConfig, database: &str) {
    let sql = "\
        DROP SCHEMA IF EXISTS fluxdb_ai_smoke CASCADE; \
        CREATE SCHEMA fluxdb_ai_smoke; \
        CREATE TABLE fluxdb_ai_smoke.customers( \
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
            name text NOT NULL); \
        CREATE TABLE fluxdb_ai_smoke.orders( \
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
            customer_id integer NOT NULL REFERENCES fluxdb_ai_smoke.customers(id), \
            amount numeric(12,2) NOT NULL, \
            note text); \
        CREATE INDEX idx_fluxdb_ai_orders_customer ON fluxdb_ai_smoke.orders(customer_id); \
        COMMENT ON TABLE fluxdb_ai_smoke.orders IS 'T023 orders'; \
        INSERT INTO fluxdb_ai_smoke.customers(name) VALUES ('acme'); \
        INSERT INTO fluxdb_ai_smoke.orders(customer_id, amount, note) \
            VALUES (1, 10.50, 'first'), (1, 20.25, 'second'); \
        CREATE VIEW fluxdb_ai_smoke.order_stats AS \
            SELECT customer_id, sum(amount) AS total \
            FROM fluxdb_ai_smoke.orders GROUP BY customer_id;";
    let execution = ai_live_exec(
        connector,
        config.id,
        Some(database.to_string()),
        None,
        sql,
    )
    .expect("T023 PG 建隔离 schema 应成功");
    ai_live_assert_all_ok(&execution, "T023 PG setup");
}

