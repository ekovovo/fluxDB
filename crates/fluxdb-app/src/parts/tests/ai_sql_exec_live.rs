/// 真实连接上的 resolver：只用非敏感配置，不触碰用户存储。
struct AiLiveResolver {
    config: ConnectionConfig,
    session_id: fluxdb_core::QuerySessionId,
}

impl AiLiveResolver {
    fn new(config: ConnectionConfig) -> Self {
        Self {
            config,
            session_id: fluxdb_core::QuerySessionId::host_managed(9_023),
        }
    }
}

impl SqlExecutionResolver for AiLiveResolver {
    fn connection_config(&self, id: ConnectionId) -> Option<ConnectionConfig> {
        (id == self.config.id).then(|| self.config.clone())
    }

    fn query_session_id(&self) -> fluxdb_core::QuerySessionId {
        self.session_id
    }
}

/// 真实连接器自己会建 tokio runtime；这里不能套一层 runtime（否则嵌套 runtime panic）。
/// 工具 future 不依赖外部 IO 反应堆，用生产同款「就绪轮询」阻塞器即可。
fn ai_block_on<F: std::future::Future>(future: F) -> F::Output {
    block_on_ready(future).expect("工具 future 应在就绪轮次内完成")
}
